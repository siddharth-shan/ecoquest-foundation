// Real captured air-quality windows for Cerritos, CA (ZIP 90703, 33.8669/-118.0686).
//
// Air Detective reads a year of hourly pollution data for the player's own ZIP.
// When that call fails — offline classroom, rate limit, a ZIP whose grid cell
// comes back sparse — the game still has to be playable, and it may not invent
// numbers to do it. Everything below was downloaded from the Open-Meteo Air
// Quality API on 2026-09-29 for EcoQuest's home city and pasted in unaltered
// (values rounded to one decimal, which is the precision the API returns).
//
// Whenever these are used, the page renders <DataSourceNote isFixture /> so the
// player is told plainly that they are looking at Cerritos, not at home.
//
// Units: PM2.5, PM10 and dust in ug/m3; ozone in ug/m3; temperature in degrees F.
// Hours are local time for Cerritos, 24 values per day, index 0 = midnight.

export interface FixtureWindow {
  id: string
  /** First day of the window, YYYY-MM-DD, local. */
  startDate: string
  /** The day under investigation. Always inside the window. */
  focusDate: string
  /**
   * Median daily-max PM2.5 over the seven days ending four days before the
   * focus day. Captured from the same real series, so the live detector and the
   * fixture detector see the same kind of baseline. The lead gap keeps the
   * event itself out of its own baseline.
   */
  baselinePm25Max: number
  /** Hourly PM2.5, days x 24. */
  pm25: number[]
  /** Hourly ozone, days x 24. */
  ozone: number[]
  /** Daily maxima — only the peak matters for the coarse-particle test. */
  pm10Max: number[]
  dustMax: number[]
  /** Daily maximum temperature, degrees F, from the Open-Meteo archive API. */
  tempMaxF: (number | null)[]
}

export interface FixtureCorrelation {
  startDate: string
  endDate: string
  /** One entry per day, same order, for the heat-and-ozone round. */
  tempMaxF: number[]
  ozoneMax: number[]
  pm25Max: number[]
}

